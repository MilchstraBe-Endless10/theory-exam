import { randomInt, randomUUID } from 'node:crypto';
import { chmodSync, closeSync, fsyncSync, mkdirSync, openSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, resolve } from 'node:path';
import type { DatabaseSync } from 'node:sqlite';
import { inTransaction } from './db/database.js';
import { hashPassword } from './security.js';

export interface AccountProvisionSpec {
  username: string;
  isTestAccount: boolean;
}

const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

export function createInitialPassword(now = new Date()): string {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Shanghai', year: '2-digit', month: '2-digit', day: '2-digit',
  }).formatToParts(now);
  const dateParts = Object.fromEntries(parts.map(part => [part.type, part.value]));
  const suffix = `${dateParts.year}${dateParts.month}${dateParts.day}`;
  let prefix = '';
  for (let index = 0; index < 8; index += 1) prefix += LETTERS[randomInt(LETTERS.length)];
  return `${prefix}${suffix}`;
}

function writePrivateFile(path: string, contents: string): void {
  const directory = dirname(path);
  mkdirSync(directory, { recursive: true, mode: 0o700 });
  chmodSync(directory, 0o700);
  const descriptor = openSync(path, 'wx', 0o600);
  let completed = false;
  try {
    writeFileSync(descriptor, contents, 'utf8');
    fsyncSync(descriptor);
    completed = true;
  } finally {
    closeSync(descriptor);
    if (!completed) unlinkSync(path);
  }
  chmodSync(path, 0o600);
}

export async function provisionAccounts(
  db: DatabaseSync,
  specifications: AccountProvisionSpec[],
  credentialsPath: string,
  now = new Date(),
): Promise<{ createdCount: number; credentialsPath: string }> {
  if (specifications.length !== 4 || specifications.filter(account => account.isTestAccount).length !== 1) {
    throw new Error('Provisioning requires exactly four ordinary accounts, including one marked test account.');
  }
  if (specifications.some(account => Object.keys(account).some(key => key !== 'username' && key !== 'isTestAccount'))) {
    throw new Error('Manifest entries may contain only username and isTestAccount; passwords are generated by the server.');
  }
  const normalized = specifications.map(account => ({ username: account.username.trim(), isTestAccount: account.isTestAccount }));
  if (normalized.some(account => !account.username || account.username.length > 64 || /\s/.test(account.username))) {
    throw new Error('Usernames must contain 1–64 non-whitespace characters.');
  }
  if (new Set(normalized.map(account => account.username.toLocaleLowerCase())).size !== normalized.length) {
    throw new Error('Provisioning manifest contains duplicate usernames.');
  }
  const outputPath = resolve(credentialsPath);
  if (!isAbsolute(credentialsPath) || outputPath.startsWith(`${resolve(process.cwd())}/`)) {
    throw new Error('Credentials must be written to an absolute path outside the project checkout.');
  }
  const placeholders = normalized.map(() => '?').join(', ');
  const existing = db.prepare(`SELECT username FROM users WHERE username COLLATE NOCASE IN (${placeholders})`)
    .all(...normalized.map(account => account.username));
  if (existing.length) throw new Error('At least one requested username already exists; no accounts were changed.');

  const passwords = new Set<string>();
  const issued = normalized.map(account => {
    let password = createInitialPassword(now);
    while (passwords.has(password)) password = createInitialPassword(now);
    passwords.add(password);
    return { ...account, password };
  });
  const hashed = await Promise.all(issued.map(async account => ({ ...account, passwordHash: await hashPassword(account.password) })));
  const createdAt = new Date().toISOString();
  let credentialsCreated = false;
  try {
    writePrivateFile(outputPath, `${JSON.stringify({
      purpose: 'one-time initial passwords; remove after secure handoff',
      createdAt,
      accounts: issued.map(({ username, isTestAccount, password }) => ({ username, isTestAccount, initialPassword: password })),
    }, null, 2)}\n`);
    credentialsCreated = true;
    inTransaction(db, () => {
      const raced = db.prepare(`SELECT 1 FROM users WHERE username COLLATE NOCASE IN (${placeholders}) LIMIT 1`)
        .get(...normalized.map(account => account.username));
      if (raced) throw new Error('A requested username was created concurrently; no accounts were changed.');
      const insert = db.prepare(`INSERT INTO users
        (id, username, password_hash, role, disabled, created_at, updated_at, must_change_password, is_test_account)
        VALUES (?, ?, ?, 'user', 0, ?, ?, 1, ?)`);
      for (const account of hashed) {
        insert.run(randomUUID(), account.username, account.passwordHash, createdAt, createdAt, Number(account.isTestAccount));
      }
    });
    return { createdCount: hashed.length, credentialsPath: outputPath };
  } catch (error) {
    if (credentialsCreated) unlinkSync(outputPath);
    throw error;
  }
}
